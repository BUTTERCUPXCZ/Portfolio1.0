/* Generates src/data/icons.js from simple-icons.
 *
 * Run it after adding a technology to `skills` in src/data/profile.js:
 *     npm run icons
 *
 * Why generate instead of importing at runtime: simple-icons is ~15 MB and
 * does not tree-shake reliably across 40 icons. Extracting only the paths we
 * use keeps it a devDependency and ships a couple of KB.
 *
 * Anything without an entry here simply renders as a label — that is a
 * supported outcome, not a failure. */

import { readFileSync, existsSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { skills } from '../src/data/profile.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const iconDir = resolve(root, 'node_modules/simple-icons/icons')

/* Stack label -> simple-icons slug. Add a line when you add a technology. */
const SLUGS = {
  JavaScript: 'javascript',
  TypeScript: 'typescript',
  Python: 'python',
  HTML: 'html5',
  CSS: 'css',
  React: 'react',
  Electron: 'electron',
  'Tailwind CSS': 'tailwindcss',
  'TanStack Query': 'reactquery',
  'Shadcn/ui': 'shadcnui',
  'Node.js': 'nodedotjs',
  NestJS: 'nestjs',
  Express: 'express',
  Flask: 'flask',
  FastAPI: 'fastapi',
  'WebSocket / Socket.IO': 'socketdotio',
  Redis: 'redis',
  PostgreSQL: 'postgresql',
  MySQL: 'mysql',
  'Prisma ORM': 'prisma',
  Supabase: 'supabase',
  NeonDB: 'neon',
  Render: 'render',
  Vercel: 'vercel',
  Docker: 'docker',
  Git: 'git',
  GitHub: 'github',
  'VS Code': 'vscodium',
  Claude: 'claude',
  Copilot: 'githubcopilot',
  Gemini: 'googlegemini',
}

if (!existsSync(iconDir)) {
  console.error('simple-icons is not installed. Run: npm install')
  process.exit(1)
}

const entries = []
const missing = []

for (const [label, slug] of Object.entries(SLUGS)) {
  const file = resolve(iconDir, `${slug}.svg`)
  if (!existsSync(file)) {
    missing.push(`${label} → ${slug}.svg`)
    continue
  }
  const path = readFileSync(file, 'utf8').match(/ d="([^"]+)"/)?.[1]
  if (!path) {
    missing.push(`${label} → no path in ${slug}.svg`)
    continue
  }
  entries.push([label, path])
}

const used = skills.flatMap((group) => group.items)
const withoutIcon = used.filter((item) => !SLUGS[item])

const out = `/* GENERATED by scripts/build-icons.mjs — do not edit by hand.
 * Run \`npm run icons\` to regenerate after changing \`skills\` in profile.js.
 * Icons are single paths on a 24x24 grid, drawn in currentColor. */

export const iconPaths = {
${entries.map(([label, d]) => `  ${JSON.stringify(label)}: ${JSON.stringify(d)},`).join('\n')}
}

export const iconFor = (label) => iconPaths[label] ?? null
`

writeFileSync(resolve(root, 'src/data/icons.js'), out)

console.log(`icons: ${entries.length} written`)
if (missing.length) console.warn(`  unresolved slugs: ${missing.join(', ')}`)
if (withoutIcon.length) {
  console.log(`  rendering as label only (${withoutIcon.length}): ${withoutIcon.join(', ')}`)
}
